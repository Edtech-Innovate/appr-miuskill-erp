                    <h4>Heat Treatment Virtual Lab</h4>
                    <p class="pb-10">In this lab users can enter the heating, cooling and tempering heat treatment cycle for virtually treating complex geometry for a defined period of time. Users are allowed to graphically evaluate microstructure property changes and predict the abnormalities likely to occur during the cycle. Participants can use the Heat Treatment Virtual Lab to perform experiments such as Annealing process of a forging die, tempering process of a test specimen.</p>

                    <h4>Thermal Engineering Virtual Lab</h4>
                    <p class="pb-10">Thermal simulation enables to study how systems will behave in the real world, where fluid is the driving factor. Virtual lab is the platform which does experience the variation of practical output by changing input properties on components and allow users to examine extensively all possible variations in the design and optimization of systems. Participants can use the Thermal Engineering Virtual Lab to perform the experiments with pumps, turbines, valves, composite pipes, fluids, gasses and other flow related components, thermodynamic components.</p>

